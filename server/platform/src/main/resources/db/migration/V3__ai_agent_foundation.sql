CREATE TABLE ai_system_configs (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    config_key VARCHAR(128) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    provider_type VARCHAR(64) NOT NULL DEFAULT '',
    base_url VARCHAR(1024) NOT NULL DEFAULT '',
    text_model VARCHAR(255) NOT NULL DEFAULT '',
    vision_model VARCHAR(255) NOT NULL DEFAULT '',
    embedding_model VARCHAR(255) NOT NULL DEFAULT '',
    api_key_ciphertext TEXT,
    credential_configured BOOLEAN NOT NULL DEFAULT FALSE,
    request_timeout_ms INT NOT NULL DEFAULT 30000,
    max_input_length INT NOT NULL DEFAULT 0,
    max_output_length INT NOT NULL DEFAULT 0,
    retry_count INT NOT NULL DEFAULT 0,
    request_logging_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    external_document_send_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    provider_config_json TEXT,
    masked_config_json TEXT,
    actor_id VARCHAR(128) NOT NULL DEFAULT 'system-dev',
    actor_name VARCHAR(255) NOT NULL DEFAULT 'Development User',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_ai_system_config_key UNIQUE (config_key)
);


    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    record_id VARCHAR(128) NOT NULL,
    run_id BIGINT,
    project_id BIGINT,
    provider_type VARCHAR(64) NOT NULL DEFAULT '',
    model_name VARCHAR(255) NOT NULL DEFAULT '',
    config_snapshot_id VARCHAR(128) NOT NULL DEFAULT '',
